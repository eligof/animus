import { test } from 'node:test';
import assert from 'node:assert/strict';
import { ChatReader } from '../src/claude/chat.ts';

const T0 = Date.UTC(2026, 9, 25, 10, 0, 0);
const at = (s: number) => new Date(T0 + s * 1000).toISOString();
// An assistant record (Claude Code writes one per block; several work too)
// and a user record, each with its own uuid.
const said = (s: number, ...content: object[]) => ({ type: 'assistant', uuid: `a${s}`, timestamp: at(s), message: { role: 'assistant', content } });
const asked = (s: number, content: unknown, extra: object = {}) => ({ type: 'user', uuid: `u${s}`, timestamp: at(s), message: { role: 'user', content }, ...extra });
const read = (...recs: unknown[]) => {
  const r = new ChatReader();
  for (const rec of recs) r.apply(rec);
  return r.bubbles().map(({ kind, text, outcome }) => (outcome ? { kind, text, outcome } : { kind, text }));
};
// A message another session posted, as the receiver records it.
const peer = (s: number, name: string, body: string) =>
  asked(s, `Another Claude session sent a message:\n<cross-session-message from-name="${name}">\n${body}\n</cross-session-message>`, {
    isMeta: true,
    turnOrigin: 'peer',
    promptSource: 'system',
    origin: { kind: 'peer', from: 'unknown', verifiedPeerPid: 1, name, body },
  });

test('replies, prompts and tool steps, in order', () => {
  assert.deepEqual(
    read(
      asked(0, 'Fix the tokenizer edge case'),
      said(1, { type: 'text', text: 'Looking at the parser.' }),
      said(2, { type: 'tool_use', id: 't1', name: 'Bash', input: { command: 'npm test' } }),
      asked(3, [{ type: 'tool_result', tool_use_id: 't1', content: 'ok' }]),
      said(4, { type: 'tool_use', id: 't2', name: 'Edit', input: { file_path: '/repo/src/parser.ts', old_string: 'a', new_string: 'b' } }),
      said(5, { type: 'text', text: 'Done.' }),
    ),
    [
      { kind: 'user', text: 'Fix the tokenizer edge case' },
      { kind: 'agent', text: 'Looking at the parser.' },
      { kind: 'tool', text: '$ npm test', outcome: 'ok' },
      { kind: 'tool', text: 'Edit parser.ts', outcome: 'pending' },
      { kind: 'agent', text: 'Done.' },
    ],
  );
});

test('a failed step is marked failed; one refused or interrupted is marked refused', () => {
  const steps = read(
    said(1, ...['a', 'b', 'c', 'd'].map((id) => ({ type: 'tool_use', id, name: 'Bash', input: { command: `step ${id}` } }))),
    asked(2, [{ type: 'tool_result', tool_use_id: 'a', is_error: true, content: 'Exit code 1' }]),
    asked(3, [{ type: 'tool_result', tool_use_id: 'b', is_error: true, content: 'PreToolUse:Bash hook error: blocked' }]),
    asked(4, [{ type: 'tool_result', tool_use_id: 'c', is_error: true, content: [{ type: 'text', text: "The user doesn't want to proceed with this tool use. The tool use was rejected." }] }]),
    asked(5, [{ type: 'tool_result', tool_use_id: 'd', is_error: true, content: '[Request interrupted by user for tool use]' }]),
  );
  assert.deepEqual(steps.map((b) => b.outcome), ['failed', 'refused', 'refused', 'refused']);
});

test('thinking shows as a mark only, once for a run, never its words', () => {
  const r = new ChatReader();
  r.apply(said(1, { type: 'thinking', thinking: 'secret plan', signature: 'x' }));
  r.apply(said(2, { type: 'redacted_thinking', data: 'zzz' }));
  r.apply(said(3, { type: 'text', text: 'Hi.' }));
  r.apply(said(4, { type: 'thinking', thinking: 'more', signature: 'y' }));
  assert.deepEqual(r.bubbles().map((b) => b.kind), ['thinking', 'agent', 'thinking']);
  assert.ok(!JSON.stringify(r.bubbles()).includes('secret'));
});

test("animus's own messages come back as sent; other peers and meta records are left out", () => {
  const r = new ChatReader();
  r.apply(peer(1, 'animus', 'also add a test'));
  r.apply(peer(2, 'someone-else', 'hello'));
  r.apply(asked(3, 'Caveat: the messages below were generated by the user', { isMeta: true }));
  assert.deepEqual(
    r.bubbles().map(({ kind, text, at, peerPid }) => ({ kind, text, at, peerPid })),
    [{ kind: 'sent', text: 'also add a test', at: T0 + 1000, peerPid: 1 }],
  );
});

test('a sent message keeps the pid its receiver verified sent it, when the record has one', () => {
  const r = new ChatReader();
  r.apply({ ...peer(1, 'animus', 'no pid'), origin: { kind: 'peer', name: 'animus', body: 'no pid' } });
  r.apply({ ...peer(2, 'animus', 'odd pid'), uuid: 'x', origin: { kind: 'peer', name: 'animus', body: 'odd pid', verifiedPeerPid: 'one' } });
  assert.deepEqual(r.bubbles().map((b) => [b.text, b.peerPid]), [['no pid', undefined], ['odd pid', undefined]]);
});

test('prompts Claude Code wrote itself are left out', () => {
  assert.deepEqual(
    read(
      asked(1, '<task-notification>\n<task-id>x</task-id>\n<status>completed</status>\n</task-notification>'),
      asked(2, '<command-name>/clear</command-name>'),
      asked(3, '<local-command-stdout>done</local-command-stdout>'),
      asked(4, '[Request interrupted by user]'),
      asked(5, [{ type: 'text', text: 'and a prompt with an image' }, { type: 'image', source: {} }]),
    ),
    [{ kind: 'user', text: 'and a prompt with an image' }],
  );
});

test('ids are stable per record and block; the newest 300 are kept; a huge reply is cut', () => {
  const r = new ChatReader();
  r.apply(said(1, { type: 'text', text: 'a' }, { type: 'text', text: 'b' }));
  assert.deepEqual(r.bubbles().map((b) => b.id), ['a1:0', 'a1:1']);
  for (let i = 0; i < 400; i++) r.apply(asked(10 + i, `prompt ${i}`));
  assert.equal(r.bubbles().length, 300);
  assert.equal(r.bubbles()[299].text, 'prompt 399');
  r.apply(said(999, { type: 'text', text: 'x'.repeat(50_000) }));
  assert.equal(r.bubbles()[299].text.length, 20_001);
});

test('records it cannot read change nothing', () => {
  const r = new ChatReader();
  const junk = [null, 7, 'x', {}, { type: 'assistant' }, { type: 'assistant', message: { content: 'nope' } }, { type: 'user', message: { content: [{ type: 'tool_result', tool_use_id: 'never' }] } }, { type: 'ai-title', aiTitle: 't' }];
  for (const rec of junk) r.apply(rec);
  assert.deepEqual(r.bubbles(), []);
});

test('a peer message without isMeta is still a peer message, never a prompt', () => {
  const plain = (s: number, name: string, body: string) => {
    const { isMeta: _m, ...rest } = peer(s, name, body) as Record<string, unknown>;
    return rest;
  };
  const r = new ChatReader();
  r.apply(plain(1, 'animus', 'from animus'));
  r.apply(plain(2, 'someone-else', 'from another'));
  assert.deepEqual(r.bubbles().map(({ kind, text }) => ({ kind, text })), [{ kind: 'sent', text: 'from animus' }]);
});

test('a record seen twice (replayed, resumed) adds nothing the second time', () => {
  const r = new ChatReader();
  const recs = [asked(1, 'Hi'), said(2, { type: 'text', text: 'Hello.' }), peer(3, 'animus', 'more')];
  for (const rec of [...recs, ...recs]) r.apply(rec);
  const ids = r.bubbles().map((b) => b.id);
  assert.equal(ids.length, 3);
  assert.equal(new Set(ids).size, 3);
});
